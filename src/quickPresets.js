// Built-in Quick Presets.
//
// These three complete visual snapshots are the user's saved looks, exposed
// under stable public names. Applying one replaces the full visual snapshot;
// window behaviour and lyric-sync controls are not part of a look.
//
// Do not add media-provider, room, or game behaviour here. This module only
// supplies appearance values to the existing quick-preset UI.

function freezePreset(preset) {
  return Object.freeze({
    ...preset,
    glass: Object.freeze({ ...preset.glass }),
    cfg: Object.freeze({ ...preset.cfg }),
  })
}

