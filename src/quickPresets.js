export const QUICK_PRESET_IDS = Object.freeze(Object.keys(QUICK_PRESETS))

// Glass and cfg must be applied together. A preset that only wrote cfg would
// leave the previous look's glass parameters in place.
export function applyQuickPreset(id, { setCfg, setGlass }) {
  const preset = QUICK_PRESETS[id]
  if (!preset) return false
  if (preset.glass && setGlass) setGlass({ ...preset.glass })
  if (preset.cfg && setCfg) setCfg({ ...preset.cfg })
  return true
}
